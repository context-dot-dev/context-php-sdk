<?php

declare(strict_types=1);

namespace ContextDev\Browser\Profiles;

use ContextDev\Core\Attributes\Optional;
use ContextDev\Core\Concerns\SdkModel;
use ContextDev\Core\Concerns\SdkParams;
use ContextDev\Core\Contracts\BaseModel;

/**
 * List the browser profiles your organization saved through `POST /web/scrape`, newest first. Pass a profile `id` as `sharedParams.profile.profileId` to scrape as that signed-in user.
 *
 * @see ContextDev\Services\Browser\ProfilesService::list()
 *
 * @phpstan-type ProfileListParamsShape = array{
 *   cursor?: string|null, limit?: int|null
 * }
 */
final class ProfileListParams implements BaseModel
{
    /** @use SdkModel<ProfileListParamsShape> */
    use SdkModel;
    use SdkParams;

    /**
     * Cursor from the previous page's `next_cursor`. Omit for the first page.
     */
    #[Optional]
    public ?string $cursor;

    /**
     * Maximum number of profiles to return per page.
     */
    #[Optional]
    public ?int $limit;

    public function __construct()
    {
        $this->initialize();
    }

    /**
     * Construct an instance from the required parameters.
     *
     * You must use named parameters to construct any parameters with a default value.
     */
    public static function with(?string $cursor = null, ?int $limit = null): self
    {
        $self = new self;

        null !== $cursor && $self['cursor'] = $cursor;
        null !== $limit && $self['limit'] = $limit;

        return $self;
    }

    /**
     * Cursor from the previous page's `next_cursor`. Omit for the first page.
     */
    public function withCursor(string $cursor): self
    {
        $self = clone $this;
        $self['cursor'] = $cursor;

        return $self;
    }

    /**
     * Maximum number of profiles to return per page.
     */
    public function withLimit(int $limit): self
    {
        $self = clone $this;
        $self['limit'] = $limit;

        return $self;
    }
}
